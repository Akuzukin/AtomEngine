using System.Security;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
if(args.Length!=2)throw new ArgumentException("Usage: AssetCodegen audio-directory output.cs");
var directory=Path.GetFullPath(args[0]);var output=Path.GetFullPath(args[1]);
if(!Directory.Exists(directory))throw new DirectoryNotFoundException(directory);
var files=Directory.EnumerateFiles(directory,"*",SearchOption.AllDirectories)
    .Where(p=>Path.GetExtension(p).Equals(".mp3",StringComparison.OrdinalIgnoreCase)||Path.GetExtension(p).Equals(".wav",StringComparison.OrdinalIgnoreCase))
    .Select(p=>Path.GetRelativePath(directory,p).Replace('\\','/')).Order(StringComparer.Ordinal).ToArray();
string Identifier(string relative) {
    var parts=Regex.Split(relative,@"[^\p{L}\p{Nd}_]+",RegexOptions.CultureInvariant).Where(p=>p.Length!=0);
    var name=string.Join("",parts.Select(p=>char.ToUpperInvariant(p[0])+p[1..]));
    if(name.Length==0 || char.IsDigit(name[0]))name="Clip"+name;return name;
}
var names=files.GroupBy(Identifier).ToDictionary(g=>g.Key,g=>g.Count(),StringComparer.Ordinal);
var source=new StringBuilder("// <auto-generated />\nusing Atom;\nnamespace Game.Assets;\n/// <summary>脚本构建时扫描生成的音频资源；新增、删除或重命名文件后重新构建以更新成员。</summary>\npublic static class AudioAssets\n{\n");
var used=new HashSet<string>(StringComparer.Ordinal);
foreach(var relative in files) {
    var name=Identifier(relative);if(names[name]>1)name+="_"+Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(relative)))[..12];
    if(!used.Add(name))throw new InvalidOperationException("Audio identifier collision: "+relative);
    var path="Asset/Sounds/"+relative;
    source.Append("    /// <summary>音频资源：").Append(SecurityElement.Escape(path)).Append("</summary>\n    public static AudioClip ").Append(name).Append(" => new(").Append(JsonSerializer.Serialize(path)).Append(");\n");
}
source.Append("}\n");Directory.CreateDirectory(Path.GetDirectoryName(output)!);
if(!File.Exists(output)||File.ReadAllText(output)!=source.ToString())File.WriteAllText(output,source.ToString(),new UTF8Encoding(false));
Console.WriteLine($"Audio catalog: {files.Length} clips");
